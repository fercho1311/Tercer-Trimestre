public class Correo {

    String origen;
    String destino;
    String titulo;
    String contenido;
    String fecha;

    public Correo(String origen, String destino, String titulo, String contenido, String fecha) {
        this.origen = origen;
        this.destino = destino;
        this.titulo = titulo;
        this.contenido = contenido;
        this.fecha = fecha;
    }
}