public class Casa {
    private String alto, ancho;

    public void definirAlto(String alto){
        this.alto = alto;
    }

    public void definirAncho(String ancho){
        this.ancho = ancho;
    }

    public String definirAlto(){
        return this.alto;
    }

    public String definirAncho(){
        return this.ancho;
    }
}
